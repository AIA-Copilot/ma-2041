import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = path.resolve(process.argv[2] || 'finished');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
const app = JSON.parse(read('appPackage/manifest.json'));
const da = JSON.parse(read('appPackage/declarativeAgent.json'));
assert.equal(app.copilotAgents.declarativeAgents[0].file, 'declarativeAgent.json');
assert.equal(da.version, 'v1.9');
assert.equal(da.name, 'Zava Travel Assistant');
assert.equal(da.instructions, "$[file('instruction.txt')]");
assert.equal(da.conversation_starters.length, 3);
assert.deepEqual(da.capabilities.map(c => c.name), ['WebSearch', 'GraphConnectors']);
const connection = da.capabilities[1].connections[0].connection_id;
assert.match(connection, /^[A-Za-z0-9]+$/, 'Use the actual alphanumeric Lab 3 connection ID');
assert.ok(!connection.includes('REPLACE'), 'Replace the connection placeholder');
assert.deepEqual(da.actions, [{id:'currencyMCP', file:'currency-plugin.mcp.json'}]);
const plugin = JSON.parse(read('appPackage/currency-plugin.mcp.json'));
assert.equal(plugin.runtimes[0].type, 'RemoteMCPServer');
assert.ok(app.validDomains.includes('mcp.frankfurter.dev'));
assert.ok(read('appPackage/instruction.txt').includes('Frankfurter MCP'));
console.log('PASS: local content/reference check only; not WIQD or tenant acceptance.');
